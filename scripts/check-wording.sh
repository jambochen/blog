#!/usr/bin/env bash
set -euo pipefail
export LC_ALL=C.UTF-8
cd "$(dirname "$0")/.."

# 每條規則是「不用的詞=改用的詞」。「安裝程式」指 installer，「程式語言」指 programming language，意思不同，所以排除。
rules=(
  '(?<!安裝)程式(?!語言)碼?=code'
  '代碼=code'
  '運行=執行'
  '賬號=帳號'
  '用戶=使用者'
  '文檔=文件'
  '並行計算=平行運算'
  '並行=平行、平行化'
  '環境配置=環境設定'
  '爲=為'
  '着=著'
  '窗口=視窗，或 context window'
  '搜索=搜尋'
  # 語體：作者要的是精煉的白話。例外是固定的詞：反之亦然、權宜、便宜、適宜、事宜。
  # 「並無」「即為」沒有列入，因為作者親筆的〈離開網頁對話〉前言用了這兩個詞。
  '(?<!反之)亦=也'
  '(?<![權便適事])宜=應'
  '皆=都'
  '無從=無法'
  '此即=這就是'
  '緣由=原因'
  '此事=這件事'
  '何者=哪一個、哪些'
  # 連接詞同樣用白話。例外是固定的詞：因故、事故、緣故、故事、故意、故障。
  '(?<![因事緣])故(?![事意障])=因此、所以'
  '若=如果'
  # 結論直述，不先鋪表象再翻轉，事物也不擬人。「看似……卻」沒有列入，因為如實描述表象時也用得到。
  '問的[卻都]?是=直接寫出結論'
  '說到底=直接寫出結論'
  '歸根究[柢底]=直接寫出結論'
  '真正的問題=直接寫出結論'
  '(原則|規矩|重點|關鍵|要求)(就)?只有一[條個項點件]=直接寫出內容，如「原則是……」'
  # 跨篇回指用篇名，增刪一篇時其餘各篇才不必跟著改。
  '第 ?[0-9]+ ?篇=篇名，如[[版本控制]]一篇'
  '(?<!以)[上下]一?篇(?![幅章])=篇名，如[[版本控制]]一篇'
  '第[一二三四五] ?部(?!分)=部名，如「該知道的 CS 工具」一部'
)

# 草稿尚未定稿，不檢查。
mapfile -t posts < <(grep -rLE '^draft: *true' --include='*.md' --include='*.mdx' src/content/blog/coding-agent)

status=0
for rule in "${rules[@]}"; do
  pattern=${rule%%=*}
  replacement=${rule#*=}
  if matches=$(grep -nP "$pattern" "${posts[@]}"); then
    printf '改用「%s」：\n%s\n\n' "$replacement" "$matches"
    status=1
  fi
done
exit $status
